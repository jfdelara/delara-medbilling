def sha(p): return hashlib.sha256(open(p, 'rb').read()).hexdigest() if os.path.exists(p) else ''

def fetch(url, dest):
    tmp = dest + '.new'
    r = subprocess.run(['curl', '-sSL', '-A', UA, '--retry', '2', '-m', '300', '-o', tmp, '-w', '%{http_code}', url], capture_output=True, text=True)
    if r.stdout.strip() != '200' or not os.path.exists(tmp) or open(tmp, 'rb').read(5) != b'%PDF-':
        if os.path.exists(tmp): os.remove(tmp)
        return None
    return tmp

def main():
    offline = '--offline' in sys.argv
    ck_path = os.path.join(RAW, 'checked.json')
    checked = json.load(open(ck_path)) if os.path.exists(ck_path) else {}
    today = datetime.date.today().isoformat()
    report = []
    for jid, s in SOURCES.items():
        dest = os.path.join(RAW, s['file'])
        if offline: report.append(f'{jid}: offline, using {s["file"]}'); continue
        ed = ''
        if s.get('landing'):
            r = subprocess.run(['curl', '-sSL', '-A', UA, '-m', '60', s['landing']], capture_output=True, text=True)
            m = re.search(s.get('edition_re', '$^'), r.stdout, s.get('edition_flags', 0))
            ed = m.group(s.get('edition_group', 1)) if m else '(edition text not found on landing page)'
            if m and m.lastindex and m.lastindex >= 2 and s.get('link_key', s['url']) not in m.group(1):
                ed += f' (NEWEST LINK DIFFERS: {m.group(1)}; update url, file and build_{jid.lower()})'
        tmp = fetch(s['url'], dest)
        if not tmp: report.append(f'{jid}: DOWNLOAD FAILED, kept previous file. NEEDS ATTENTION'); continue
        old, new = sha(dest), sha(tmp)
        os.replace(tmp, dest)
        checked[s['file']] = today
        report.append(f'{jid}: {"NEW EDITION (file changed)" if old != new else "unchanged"}; landing says: {ed}')
    os.makedirs(RAW, exist_ok=True)
    json.dump(checked, open(ck_path, 'w'), indent=1)
    if '--download-only' in sys.argv:  # data-pipeline.py rebuilds only the sources it could fetch
        print('\n'.join(report)); return
    subprocess.run([sys.executable, os.path.join(HERE, 'build_prov.py')], check=True)
    for jid in SOURCES:
        subprocess.run([sys.executable, os.path.join(HERE, 'spotcheck.py'), jid], check=False)
    print('\n'.join(report))
    print('\nManual steps:'); [print(f'  {k}: {v}') for k, v in MANUAL.items()]

if __name__ == '__main__':
    main()

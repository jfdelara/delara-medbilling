#!/usr/bin/env python3
"""Monthly refresh of the province/territory sources, then rebuild site/data/prov/*.json and re-run the spot-checks.

    python3 scripts/provinces/update_provinces.py            # download each live source, rebuild, spot-check
    python3 scripts/provinces/update_provinces.py --offline  # rebuild from files already in raw/provinces/
    python3 scripts/provinces/update_provinces.py --download-only  # fetch + report only (scripts/data-pipeline.py)

A new edition is detected by the file's SHA-256 changing (and, where the landing page names the edition, by that text).
If a download fails or is not a PDF, the previous file is kept and the jurisdiction is reported as needing attention.
Manual steps are listed in MANUAL below and printed at the end of every run."""
